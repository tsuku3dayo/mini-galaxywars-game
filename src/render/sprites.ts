/** 爆発 32 × 32。2 枚（広がる前・広がったあと） */
export const EXPLOSION = [10, 15].map((radius) =>
  plain(
    Array.from({ length: 32 }, (_, y) =>
      Array.from({ length: 32 }, (_, x) => {
        const dx = x - 15.5;
        const dy = y - 15.5;
        const d = Math.hypot(dx, dy);
        // 8 方向の光の筋と、ちらばった粒
        const ray = Math.abs(dx) < 1.5 || Math.abs(dy) < 1.5 || Math.abs(Math.abs(dx) - Math.abs(dy)) < 1.5;
        const speck = (x * 7 + y * 13) % 5 === 0;
        return d <= radius && (ray || (speck && d > radius / 3)) ? '#' : '.';
      }).join(''),
    ),
  ),
);

