import { METEOR_SIZE, UFO_FRAME_STEPS } from '../core/config';

export interface Sprite {
  w: number;
  h: number;
  rows: string[];
}

/** 左半分の行を左右対称にして 1 枚の絵にする */
function mirrored(halfRows: string[]): Sprite {
  const rows = halfRows.map((r) => r + [...r].reverse().join(''));
  return { w: rows[0]!.length, h: rows.length, rows };
}

function plain(rows: string[]): Sprite {
  return { w: rows[0]!.length, h: rows.length, rows };
}

